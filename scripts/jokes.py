def run_number(d: date) -> int:
    """Editions since BANK_START: Mon–Wed is the Monday edition, Thu–Sun the
    Thursday one. Goes up by exactly 1 per scheduled run."""
    weeks = (d - BANK_START).days // 7
    edition = 0 if d.weekday() <= 2 else 1
    return 2 * weeks + edition


def get_joke(d: date | None = None) -> str:
    """The joke for the edition on date d (defaults to today)."""
    if d is None:
        d = date.today()
    return JOKES[max(run_number(d), 0) % len(JOKES)]


def jokes_left(d: date | None = None) -> int:
    """How many editions until the bank starts repeating."""
    if d is None:
        d = date.today()
    return len(JOKES) - 1 - max(run_number(d), 0)


